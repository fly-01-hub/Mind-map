import { expect, type Page } from '@playwright/test'

const text = '普通内容，重要结论，后续内容 [[颜色测试目标]]'

// Real isolated UI interactions, shared by browser, Electron and Android assets.
export async function checkTextColors(page: Page, screenshots: string, touchPalette = false) {
  const chooseColor = async (name: string) => {
    const button = page.getByRole('toolbar', { name: '选中文字颜色' }).getByRole('button', { name, exact: true })
    if (touchPalette) await button.tap()
    else await button.click()
  }
  await page.getByRole('button', { name: '新建思维导图' }).first().click()
  await page.getByLabel('文档名称', { exact: true }).fill('文字颜色调试')
  await page.getByRole('button', { name: '导图', exact: true }).click()
  await page.locator('.me-tpc').first().click()
  await page.getByRole('button', { name: '添加子主题', exact: true }).click()
  const editor = page.locator('#input-box[contenteditable]')
  await editor.fill(text)
  await editor.press('Home')
  for (let i = 0; i < 5; i++) await editor.press('ArrowRight')
  for (let i = 0; i < 4; i++) await editor.press('Shift+ArrowRight')
  await expect.poll(() => page.evaluate(() => window.getSelection()?.toString())).toBe('重要结论')
  const toolbar = page.getByRole('toolbar', { name: '选中文字颜色' })
  await expect(toolbar).toBeVisible()
  await editor.dispatchEvent('compositionstart')
  await expect(toolbar).toBeHidden()
  await editor.dispatchEvent('compositionend')
  await expect(toolbar).toBeVisible()
  await editor.press('Control+b')
  await chooseColor('红色文字')
  await expect(editor).toBeFocused()
  await expect(editor).toHaveText(text)
  const colored = editor.locator('font[color], span[style*="color"]').filter({ hasText: '重要结论' }).first()
  await expect(colored).toHaveText('重要结论')
  await expect(colored).toHaveCSS('color', 'rgb(178, 71, 62)')
  await expect(colored).toHaveCSS('font-weight', '700')
  await page.screenshot({ path: `${screenshots}-selection.png` })
  await editor.press('Control+z')
  await expect.poll(() => editor.locator('font[color="#b2473e"], span[style*="178, 71, 62"]').count()).toBe(0)
  await editor.press('Control+Shift+z')
  await expect(editor.locator('font[color], span[style*="color"]').filter({ hasText: '重要结论' }).first()).toHaveCSS('color', 'rgb(178, 71, 62)')
  await editor.press('Escape')
  await expect(toolbar).toBeHidden()
  const topic = page.locator('.me-tpc', { hasText: '普通内容' })
  await expect(topic.locator('span[style*="color"]')).toHaveText('重要结论')
  await expect(topic.locator('span[style*="color"]')).toHaveCSS('color', 'rgb(178, 71, 62)')
  await page.getByRole('button', { name: '大纲', exact: true }).click()
  const outline = page.getByRole('textbox', { name: '主题内容', exact: true }).filter({ hasText: '普通内容' })
  await expect(outline.locator('span[style*="color"]')).toHaveText('重要结论')
  await expect(outline.locator('span[style*="color"]')).toHaveCSS('color', 'rgb(178, 71, 62)')
  await expect(page.locator('.save-status')).toContainText('已保存到本地')
  await page.reload()
  await expect(outline.locator('span[style*="color"]')).toHaveCSS('color', 'rgb(178, 71, 62)')
  await page.getByRole('button', { name: '导图', exact: true }).click()
  await expect(topic.locator('span[style*="color"]')).toHaveCSS('color', 'rgb(178, 71, 62)')
  // A real mouse drag can select text too (not just keyboard selections).
  await topic.dblclick()
  const points = await editor.evaluate((element) => {
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT)
    let node: Node | null
    while ((node = walker.nextNode())) {
      if (node.textContent !== '重要结论') continue
      const range = document.createRange()
      range.selectNodeContents(node)
      const rect = range.getBoundingClientRect()
      return { x: rect.x, y: rect.y + rect.height / 2, width: rect.width }
    }
    throw new Error('Selected text is missing')
  })
  await page.mouse.move(points.x + .5, points.y)
  await page.mouse.down()
  await page.mouse.move(points.x + points.width - .5, points.y, { steps: 8 })
  await page.mouse.up()
  await expect.poll(() => page.evaluate(() => window.getSelection()?.toString())).toBe('重要结论')
  await expect(toolbar).toBeVisible()
  await chooseColor('恢复正文颜色')
  await expect(editor.locator('b, strong').filter({ hasText: '重要结论' }).first()).toHaveCSS('font-weight', '700')
  await editor.press('Escape')
  await expect(topic.locator('span[style*="color"]')).toHaveCount(0)
  // Reapply, then verify the ordinary formatting did not create/link a map.
  await topic.dblclick()
  await editor.press('Home')
  for (let i = 0; i < 5; i++) await editor.press('ArrowRight')
  for (let i = 0; i < 4; i++) await editor.press('Shift+ArrowRight')
  await chooseColor('蓝色文字')
  await editor.press('Escape')
  await page.screenshot({ path: `${screenshots}-saved.png` })
  const currentUrl = page.url()
  const wiki = topic.locator('.wiki-link[data-wiki-name="颜色测试目标"]')
  await wiki.dblclick()
  await expect(page.getByLabel('文档名称', { exact: true })).toHaveValue('颜色测试目标')
  await page.goto(currentUrl)
  await expect(topic.locator('span[style*="color"]')).toHaveCSS('color', 'rgb(53, 106, 138)')
  await page.getByRole('button', { name: '更多', exact: true }).click()
  await page.getByRole('menuitemcheckbox', { name: '只读浏览' }).click()
  await topic.dblclick()
  await expect(editor).toHaveCount(0)
  await expect(toolbar).toBeHidden()
  await expect(topic.locator('span[style*="color"]')).toHaveCSS('color', 'rgb(53, 106, 138)')
}

export async function checkContextMenu(page: Page, screenshots: string) {
  await page.getByRole('button', { name: '新建思维导图' }).first().click()
  await page.getByRole('button', { name: '导图', exact: true }).click()
  const root = page.locator('.me-tpc').first()
  await root.click({ button: 'right' })
  const menu = page.locator('.context-content').first()
  await expect(menu).toBeVisible()
  await expect(menu).toHaveCSS('opacity', '1')
  await expect(menu.getByRole('menuitem', { name: '提升一级' })).toHaveAttribute('data-disabled', '')
  expect(await menu.locator('.context-item').evaluateAll((items) => items.map((item) => {
    const label = item.querySelector('.context-label')!
    return { text: label.textContent, height: item.getBoundingClientRect().height, labelHeight: label.getBoundingClientRect().height,
      width: label.clientWidth, scroll: label.scrollWidth }
  }).filter((item) => item.height > 31 || item.labelHeight > 21 || item.width + 1 < item.scroll))).toEqual([])
  const box = (await menu.boundingBox())!
  expect(box.width).toBeLessThanOrEqual(321)
  expect(box.height).toBeLessThan(450)
  await page.screenshot({ path: `${screenshots}-menu.png` })
  await menu.getByRole('menuitem', { name: '丰富内容' }).hover()
  await expect(page.getByRole('menuitem', { name: '添加数学公式' })).toBeVisible()
  await expect(page.locator('.context-subcontent')).toHaveCSS('opacity', '1')
  await page.screenshot({ path: `${screenshots}-submenu.png` })
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await root.click({ button: 'right' })
  await menu.getByRole('menuitem', { name: '插入下级主题' }).click()
  await page.locator('#input-box').fill('右键菜单子主题')
  await page.locator('#input-box').press('Escape')
  await expect(page.locator('.me-tpc')).toHaveCount(2)
  const child = page.locator('.me-tpc', { hasText: '右键菜单子主题' })
  await child.click({ button: 'right' })
  await expect(menu.getByRole('menuitem', { name: '提升一级' })).not.toHaveAttribute('data-disabled', '')
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 1024, height: 400 })
  await child.click({ button: 'right' })
  await expect(menu).toBeVisible()
  const small = (await menu.boundingBox())!
  expect(small.y).toBeGreaterThanOrEqual(0)
  expect(small.y + small.height).toBeLessThanOrEqual(400)
  await page.screenshot({ path: `${screenshots}-short-menu.png` })
  await menu.getByRole('menuitem', { name: '丰富内容' }).scrollIntoViewIfNeeded()
  await menu.getByRole('menuitem', { name: '丰富内容' }).hover()
  await expect(page.getByRole('menuitem', { name: '添加数学公式' })).toBeVisible()
}
