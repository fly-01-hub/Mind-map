test('protects linked annotation deletion and restores it without losing references', async ({ page }) => {
  await setup(page)
  const card = page.locator('.knowledge-annotation-card')
  await card.getByRole('button', { name: '关联当前节点 · 子项甲三' }).click()
  await expect(card.locator('.annotation-node-link')).toHaveCount(1)
  page.once('dialog', (dialog) => dialog.dismiss())
  await card.getByRole('button', { name: '删除标注 ResearchMind first page' }).click()
  await expect(card).toHaveCount(1)
  page.once('dialog', (dialog) => dialog.accept())
  await card.getByRole('button', { name: '删除标注 ResearchMind first page' }).click()
  await expect(card).toHaveCount(0)
  await page.locator('.knowledge-feedback').getByRole('button', { name: '撤销', exact: true }).click()
  await expect(card.locator('.annotation-node-link')).toHaveCount(1)
  await expect(page.locator('.paper-annotation-mark.highlight')).toHaveCount(1)
  const note = card.getByRole('textbox', { name: '批注笔记' })
  await note.fill('保留 这部分删除 留下')
  await note.press('Home'); await note.press('Control+ArrowRight'); await note.press('Control+Shift+ArrowRight'); await note.press('Backspace'); await note.press('Tab')
  await expect(note).not.toHaveValue('保留 这部分删除 留下')
  await page.reload()
  await expect(card.locator('.annotation-node-link')).toHaveCount(1)
})
