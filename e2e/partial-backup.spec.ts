import { readFile } from 'node:fs/promises'
import { expect, test } from './fixtures'

test('exports a selected map and imports selected maps from partial and full backups without replacing the library', async ({ page }) => {
  await page.evaluate(() => Reflect.deleteProperty(window, 'showSaveFilePicker'))
  await page.getByRole('button', { name: '备份与恢复' }).click()
  await page.getByRole('button', { name: /备份部分导图/ }).click()
  await page.getByRole('checkbox', { name: '选择导图 测试导图甲', exact: true }).check()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出所选导图', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/\.rmpart$/)
  const buffer = await readFile((await download.path())!)
  const payload = JSON.parse(buffer.toString())
  expect(payload.tables.documents.map((d: { id: string }) => d.id)).toEqual(['test-map'])
  await page.locator('input[accept=".rmpart,.researchmind"]').setInputFiles({ name: 'selected.rmpart', mimeType: 'application/json', buffer })
  await expect(page.getByRole('group', { name: '选择要导入的导图' })).toBeVisible()
  await expect(page.getByRole('checkbox')).toHaveCount(1)
  await page.getByRole('button', { name: '新增所选导图', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已新增 1 份导图')
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(page.getByText('测试导图甲 (2)', { exact: true })).toBeVisible()
  await expect(page.locator('.document-row')).toHaveCount(4)
  await page.getByRole('button', { name: '备份与恢复' }).click()
  const full = await page.evaluate(async () => {
    const { createLocalBackup } = await import('/src/services/backup/localBackupService.ts')
    return (await createLocalBackup()).blob.text()
  })
  const fullFile = { name: 'full.researchmind', mimeType: 'application/json', buffer: Buffer.from(full) }
  await page.locator('input[accept=".rmpart,.researchmind"]').setInputFiles(fullFile)
  await page.getByRole('button', { name: '清空选择', exact: true }).click()
  await page.getByRole('checkbox', { name: '选择导图 测试导图乙', exact: true }).check()
  await page.getByRole('button', { name: '新增所选导图', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已新增 1 份导图')
  await page.locator('input[accept=".rmpart,.researchmind"]').setInputFiles(fullFile)
  await page.getByRole('button', { name: '清空选择', exact: true }).click()
  await page.getByRole('checkbox', { name: '选择导图 测试导图乙', exact: true }).check()
  await page.getByRole('button', { name: '新增所选导图', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已新增 0 份导图')
  await expect(page.getByRole('status')).toContainText('跳过 1 份')
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.reload()
  await expect(page.locator('.document-row')).toHaveCount(5)
  await page.getByText('测试导图甲', { exact: true }).click()
  await expect(page.getByRole('textbox', { name: '文档名称', exact: true })).toHaveValue('测试导图甲')
})
